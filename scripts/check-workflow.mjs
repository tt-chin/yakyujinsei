// Uses the YAML parser already bundled with the approved pinned Playwright.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import path from 'node:path';
const req=createRequire(import.meta.url);
const modulePath=process.argv.find(a=>a.startsWith('--playwright='))?.slice(13)||process.env.PLAYWRIGHT_MODULE||'playwright';
const pwRequire=createRequire(req.resolve(modulePath));
const core=path.dirname(pwRequire.resolve('playwright-core'));
const {yaml}=req(path.join(core,'lib/utilsBundle.js'));
const workflow=yaml.parse(readFileSync(new URL('../.github/workflows/test.yml',import.meta.url),'utf8'),{uniqueKeys:true});
assert.deepEqual(workflow.on.push.branches,['dev']);
const evidenceOnly=['BACKLOG.md','docs/reviews/STAGE6_ACCEPTANCE_AUDIT.md'];
assert.deepEqual(workflow.on.push['paths-ignore'],evidenceOnly);
assert.equal(workflow.on.push.paths,undefined);
assert.deepEqual(workflow.on.pull_request.branches,['main']);
assert.equal(workflow.on.pull_request.paths,undefined);
assert.equal(workflow.on.pull_request['paths-ignore'],undefined,'PR required checks must not be path-filtered');
assert.equal(workflow.on.workflow_dispatch.paths,undefined);
assert.equal(workflow.on.workflow_dispatch['paths-ignore'],undefined);
// Exact-path model of the approved filter, not an emulation of GitHub's diff service.
const shouldRunPush=files=>files.some(file=>!evidenceOnly.includes(file));
assert.equal(shouldRunPush(evidenceOnly),false,'Only evidence updates skip dev CI');
for(const file of ['AGENTS.md','CURRENT_SPEC.md','docs/src/engine/game.js','tests/event-policy.test.mjs','tests/support/stage6-browser.mjs','scripts/test.mjs','.github/workflows/test.yml','docs/archive/README.md','docs/reviews/OTHER_REPORT.md']){
 assert.equal(shouldRunPush([file]),true,file+' must trigger CI');
 assert.equal(shouldRunPush([...evidenceOnly,file]),true,'Mixed changes must trigger CI: '+file);
}
assert.deepEqual(workflow.on.workflow_dispatch.inputs.mode.options,['quick','full','audit','linux-smoke']);
assert.equal(workflow.permissions.contents,'read');
assert.equal(workflow.concurrency['cancel-in-progress'],true);
assert.deepEqual(Object.keys(workflow.jobs),['tests','full-plan','full-batch','full-aggregate']);
const allSteps=Object.values(workflow.jobs).flatMap(j=>j.steps);
assert.ok(!allSteps.some(s=>(s.run||'').includes('--with-deps')),'No apt installs; use the pinned image');
for(const s of allSteps.filter(s=>s.uses))assert.match(s.uses,/^actions\/[a-z-]+@[0-9a-f]{40}$/,'Actions must be pinned to a full commit SHA: '+s.uses);
const pinnedImage=/^mcr\.microsoft\.com\/playwright:v(\d+\.\d+\.\d+)-noble@sha256:[0-9a-f]{64}$/;
const setup=(job,chromium)=>{
 assert.ok(!JSON.stringify(job.env||{}).includes('runner.'),'runner context is unavailable in jobs.<job_id>.env');
 assert.equal(job['runs-on'],'ubuntu-24.04');assert.equal(job['timeout-minutes'],120);
 assert.ok(job.steps.some(s=>s.with?.['node-version']==='24.15.0'));
 assert.ok(job.steps.some(s=>s.with?.['fetch-depth']===0));
 if(chromium!==undefined){
  assert.ok(job.steps.some(s=>s.run?.includes('PLAYWRIGHT_MODULE=')&&s.run.includes('$GITHUB_ENV')));
  assert.ok(job.steps.some(s=>s.run?.includes('playwright@1.62.1')&&s.run.includes('cli.js" install chromium')===chromium));
 }
 if(chromium){
  // System packages, fonts and browsers come from the digest-pinned image, not the live apt mirror.
  const image=job.container?.image?.match(pinnedImage);assert.ok(image,'Browser jobs must use the digest-pinned Playwright image');
  assert.equal(image[1],job.steps.find(s=>s.run?.includes('npm install'))?.run.match(/playwright@(\d+\.\d+\.\d+)/)?.[1],'Playwright image and npm versions differ');
  assert.equal(job.container.options,'--ipc=host');
 }else if(chromium===false)assert.equal(job.container,undefined,'full-plan stays on the host');
};
const job=workflow.jobs.tests;
assert.equal(job.if,"${{ github.event_name != 'pull_request' && inputs.mode != 'full' }}");
setup(job,true);
assert.ok(job.steps.some(s=>s.run?.includes('scripts/test.mjs')));
assert.ok(job.steps.some(s=>s.if==='always()'&&s.uses?.startsWith('actions/upload-artifact@')));
assert.ok(!job.steps.some(s=>/ci-full-batches\.mjs (plan|run|aggregate)/.test(s.run||'')),'Full must not run in the tests job');
assert.equal(job.steps.find(s=>s.name==='Run test profile').if,"env.TEST_MODE != 'full' && env.TEST_MODE != 'linux-smoke'");
assert.equal(job.steps.find(s=>s.name==='Linux Chromium smoke').if,"env.TEST_MODE == 'linux-smoke'");
const planName='tests-full-${{ github.run_id }}-${{ github.run_attempt }}-plan';
const isPlanDownload=s=>s.uses?.startsWith('actions/download-artifact@')&&s.with?.name===planName&&s.with.path==='test-results/ci-full';
const planJob=workflow.jobs['full-plan'];
assert.equal(planJob.if,"${{ github.event_name == 'pull_request' || inputs.mode == 'full' }}");
setup(planJob,false);
assert.ok(!planJob.steps.some(s=>s.run?.includes('install chromium')),'full-plan must not install Chromium');
const validate=planJob.steps.findIndex(s=>s.run==='node scripts/check-workflow.mjs');
const plan=planJob.steps.findIndex(s=>s.run==='node scripts/ci-full-batches.mjs plan');
const savePlan=planJob.steps.findIndex(s=>s.uses?.startsWith('actions/upload-artifact@')&&s.with?.name===planName);
assert.ok(validate>=0&&validate<plan&&plan<savePlan,'full-plan: validate, plan, save plan');
assert.equal(planJob.steps[savePlan].with.path,'test-results/ci-full/plan.json');
assert.equal(planJob.steps[savePlan].with['if-no-files-found'],'error');
const batchJob=workflow.jobs['full-batch'];
assert.equal(batchJob.needs,'full-plan');assert.equal(batchJob.if,undefined);
assert.equal(batchJob.strategy['fail-fast'],false);
assert.deepEqual(batchJob.strategy.matrix.batch,[1,2,3,4,5,6,7,8]);
setup(batchJob,true);
const load=batchJob.steps.findIndex(isPlanDownload);
const run=batchJob.steps.findIndex(s=>s.run==='node scripts/ci-full-batches.mjs run ${{ matrix.batch }}');
const save=batchJob.steps[run+1];
assert.ok(load>=0&&load<run,'full-batch: load plan before run');
assert.equal(batchJob.steps[run].if,undefined);assert.equal(batchJob.steps[run]['continue-on-error'],undefined);
assert.equal(save.if,'always()');assert.ok(save.uses.startsWith('actions/upload-artifact@'));
assert.equal(save.with.name,'tests-full-${{ github.run_id }}-${{ github.run_attempt }}-batch-${{ matrix.batch }}');
assert.equal(save.with['if-no-files-found'],'error');
for(const pattern of ['*.log','*.json','tmp/yakyujinsei-*/**','tmp/yakyujinsei-*.json','tmp/runner-contract-*/**'])assert.ok(save.with.path.includes('test-results/ci-full/batch-${{ matrix.batch }}/'+pattern));
assert.ok(save.with.path.includes('test-results/ci-full/plan.json'));
const aggJob=workflow.jobs['full-aggregate'];
assert.deepEqual(aggJob.needs,['full-plan','full-batch']);
assert.equal(aggJob.if,"${{ always() && needs.full-plan.result == 'success' }}");
setup(aggJob);
assert.deepEqual(aggJob.container,batchJob.container,'full-aggregate must share the full-batch container: batch summaries record absolute log paths');
const aggPlan=aggJob.steps.findIndex(isPlanDownload);
const aggBatches=aggJob.steps.findIndex(s=>s.uses?.startsWith('actions/download-artifact@')&&s.with?.pattern==='tests-full-${{ github.run_id }}-${{ github.run_attempt }}-batch-*');
assert.equal(aggJob.steps[aggBatches]?.with['merge-multiple'],true);assert.equal(aggJob.steps[aggBatches].with.path,'test-results/ci-full');
const aggregate=aggJob.steps.findIndex(s=>s.run==='node scripts/ci-full-batches.mjs aggregate');
assert.ok(aggPlan>=0&&aggBatches>=0&&Math.max(aggPlan,aggBatches)<aggregate,'full-aggregate: load plan and batches before aggregate');
assert.equal(aggJob.steps[aggregate].if,undefined);assert.equal(aggJob.steps[aggregate]['continue-on-error'],undefined);
assert.ok(aggJob.steps.slice(aggregate+1).some(s=>s.if==='always()'&&s.uses?.startsWith('actions/upload-artifact@')&&s.with.path.includes('test-results/ci-full/summary.json')));
assert.ok(!allSteps.some(s=>/git push|rsync|DEPLOY_REPO_TOKEN/.test(s.run||'')));
console.log('PASS workflow YAML parse: dev quick, main PR full, dispatch choices, pinned tools and Playwright image, full history, read-only permissions, artifacts, no deployment');
console.log('PASS exact dev evidence allowlist and mixed-change checks; PR and dispatch remain unfiltered (GitHub event execution verified separately)');
console.log('PASS parallel Full 8 batch jobs: shared attempt-scoped plan, unique batch uploads, fail-fast off, strict final aggregation after all batches; quick/audit unchanged');
