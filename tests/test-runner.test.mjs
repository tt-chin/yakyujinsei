import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import {inventory,nodeArgsFor} from '../scripts/test-manifest.mjs';
const entries=inventory(new URL('../',import.meta.url));
assert.equal(new Set(entries.map(e=>e.id)).size,entries.length,'no duplicate test entries');
for(const e of entries.filter(e=>e.modes.includes('quick')))assert.ok(e.modes.includes('full')&&e.modes.includes('audit'));
for(const e of entries.filter(e=>e.modes.includes('full')))assert.ok(e.modes.includes('audit'));
assert.deepEqual(entries.find(e=>e.id==='retirement-hof-test-support').modes,[]);
const integration=entries.find(e=>e.id==='event-integration.test');
assert.deepEqual(nodeArgsFor(integration,'darwin-arm64'),['--no-sparkplug'],'macOS arm64 runs event-integration without Sparkplug');
for(const key of ['linux-x64','darwin-x64','win32-x64'])assert.deepEqual(nodeArgsFor(integration,key),[],'no node flags on '+key);
assert.deepEqual(entries.filter(e=>e.nodeArgsByPlatform).map(e=>e.id),['event-integration.test'],'only event-integration carries node flags');
const dir=mkdtempSync(path.join(os.tmpdir(),'runner-contract-'));
function run(name,args){
  const out=path.join(dir,name),r=spawnSync(process.execPath,['scripts/test.mjs','quick',...args,'--output='+out],{encoding:'utf8'});
  assert.notEqual(r.status,0,r.stdout+r.stderr);
  return JSON.parse(readFileSync(path.join(out,'summary.json'),'utf8'));
}
const failed=run('failure',['--only=choice-action.test','--self-test-failure']);
assert.equal(failed.counts.FAIL,1);assert.equal(failed.results.at(-1).exitCode,17);assert.equal(failed.results[0].status,'PASS');
const missing=run('missing',['--only=event-fix-e2e','--playwright='+path.join(dir,'does-not-exist')]);
assert.equal(missing.counts.BLOCKED,1);assert.equal(missing.counts.PASS,0);
const cacheOut=path.join(dir,'reused');
const cached=spawnSync(process.execPath,['scripts/test.mjs','quick','--only=choice-action.test','--reuse='+path.join(dir,'failure','summary.json'),'--output='+cacheOut],{encoding:'utf8'});
assert.equal(cached.status,0,cached.stdout+cached.stderr);
const cacheReport=JSON.parse(readFileSync(path.join(cacheOut,'summary.json'),'utf8'));
assert.equal(cacheReport.executed,0);assert.equal(cacheReport.reused,1);assert.equal(cacheReport.counts.PASS,1);
const listed=spawnSync(process.execPath,['scripts/test.mjs','list'],{encoding:'utf8'});
assert.equal(listed.status,0,listed.stderr);
assert.ok(listed.stdout.includes('\n  '+['node',...nodeArgsFor(integration),integration.file].join(' ')+' \n'),'list shows the platform node flags');
const flagged=spawnSync(process.execPath,['scripts/test.mjs','quick','--only=event-integration.test','--output='+path.join(dir,'flagged')],{encoding:'utf8'});
assert.equal(flagged.status,0,flagged.stdout+flagged.stderr);
const flaggedResult=JSON.parse(readFileSync(path.join(dir,'flagged','summary.json'),'utf8')).results.find(r=>r.id==='event-integration.test');
assert.equal(flaggedResult.status,'PASS');
assert.deepEqual(flaggedResult.command,[process.execPath,...nodeArgsFor(integration),integration.file],'the executed command carries the platform node flags before the file');
console.log('PASS runner: unique inventory, profile supersets, darwin-arm64-only --no-sparkplug in list and executed command, exit 17 propagation, missing Playwright BLOCKED/nonzero, exact-source/command/log reuse');
